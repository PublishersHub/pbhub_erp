import { Stack, StackProps, RemovalPolicy, Duration, CfnOutput } from 'aws-cdk-lib';
import { Construct } from 'constructs';
import {
  Bucket,
  BucketEncryption,
  HttpMethods,
  BlockPublicAccess,
  StorageClass,
  ObjectOwnership,
} from 'aws-cdk-lib/aws-s3';
import {
  PolicyStatement,
  Effect,
  AnyPrincipal,
} from 'aws-cdk-lib/aws-iam';
import type { EnvConfig } from '../config/env-config';

interface StorageStackProps extends StackProps {
  config: EnvConfig;
}

/**
 * Single S3 bucket with prefix-based separation.
 *
 * Layout:
 *   private/
 *     receipts/{orgId}/{employeeId}/{claimId}/{filename}
 *     employee-docs/{orgId}/{employeeId}/{filename}
 *     onboarding-docs/{orgId}/{instanceId}/{taskId}/{filename}
 *   public/
 *     branding/{orgId}/logo.png, favicon.ico, login-bg.jpg
 *   cache/
 *     payslips/{orgId}/{cycleId}/{employeeId}.pdf
 *
 * Access model:
 *   - Bucket-level Block Public ACLs is ON (no object ACLs allowed).
 *   - Block Public Bucket Policy is OFF so we can grant public read on `public/*` only.
 *   - Everything else is reachable only via presigned URLs generated by the API.
 *
 * Lifecycle:
 *   - private/* — keep current versions forever; old versions delete after 90 days.
 *   - cache/* — delete after 30 days (regenerated on demand).
 *   - public/* — no expiration.
 */
export class StorageStack extends Stack {
  public readonly bucket: Bucket;

  constructor(scope: Construct, id: string, props: StorageStackProps) {
    super(scope, id, props);

    const { config } = props;
    const removalPolicy =
      config.removalPolicy === 'retain' ? RemovalPolicy.RETAIN : RemovalPolicy.DESTROY;

    this.bucket = new Bucket(this, 'AppBucket', {
      bucketName: `hr-system-${config.env}`,
      encryption: BucketEncryption.S3_MANAGED,
      versioned: config.bucketVersioning,
      enforceSSL: true,
      removalPolicy,
      autoDeleteObjects: config.removalPolicy === 'destroy',
      // Disable object ACLs entirely; we manage access via bucket policy + presigned URLs.
      objectOwnership: ObjectOwnership.BUCKET_OWNER_ENFORCED,
      // Block public ACLs but allow a public bucket policy (needed for `public/*` prefix).
      blockPublicAccess: new BlockPublicAccess({
        blockPublicAcls: true,
        ignorePublicAcls: true,
        blockPublicPolicy: false,
        restrictPublicBuckets: false,
      }),
      cors: [
        {
          allowedOrigins: config.webOrigins,
          allowedMethods: [
            HttpMethods.GET,
            HttpMethods.PUT,
            HttpMethods.POST,
            HttpMethods.HEAD,
          ],
          allowedHeaders: ['*'],
          exposedHeaders: ['ETag'],
          maxAge: 3000,
        },
      ],
      lifecycleRules: [
        // Private uploads: prune old non-current versions after 90 days
        {
          id: 'prune-old-private-versions',
          prefix: 'private/',
          enabled: true,
          noncurrentVersionExpiration: Duration.days(90),
          abortIncompleteMultipartUploadAfter: Duration.days(7),
        },
        // Cache: delete payslips after 30 days, they're regenerable
        {
          id: 'expire-payslip-cache',
          prefix: 'cache/',
          enabled: true,
          expiration: Duration.days(30),
          abortIncompleteMultipartUploadAfter: Duration.days(7),
        },
        // Long-lived documents → Standard-IA after 1 year, Glacier IR after 3 years
        {
          id: 'tier-employee-docs',
          prefix: 'private/employee-docs/',
          enabled: true,
          transitions: [
            { storageClass: StorageClass.INFREQUENT_ACCESS, transitionAfter: Duration.days(365) },
            { storageClass: StorageClass.GLACIER_INSTANT_RETRIEVAL, transitionAfter: Duration.days(1095) },
          ],
        },
      ],
    });

    // Public read on `public/*` only — branding assets fetched from the unauthenticated login screen.
    this.bucket.addToResourcePolicy(
      new PolicyStatement({
        effect: Effect.ALLOW,
        principals: [new AnyPrincipal()],
        actions: ['s3:GetObject'],
        resources: [`${this.bucket.bucketArn}/public/*`],
      }),
    );

    // S3 access lives on the EC2 instance role (compute-stack.ts), not on a
    // standalone IAM user. If we ever deploy outside AWS we can re-add a user.

    // Outputs — referenced by api .env
    new CfnOutput(this, 'BucketName', {
      value: this.bucket.bucketName,
      description: 'Set as STORAGE_S3_BUCKET in api .env',
      exportName: `hr-system-${config.env}-bucket-name`,
    });
    new CfnOutput(this, 'BucketRegion', {
      value: this.region,
      description: 'Set as STORAGE_S3_REGION in api .env',
      exportName: `hr-system-${config.env}-bucket-region`,
    });
  }
}
